const std = @import("std");
const preprocess = @import("rt/preprocess.zig");

fn writeFmt(a: std.mem.Allocator, out: *std.array_list.Managed(u8), comptime fmt: []const u8, args: anytype) !void {
    try out.appendSlice(try std.fmt.allocPrint(a, fmt, args));
}

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const a = init.arena.allocator();
    const args = try init.minimal.args.toSlice(a);

    var input: ?[]const u8 = null;
    var output: ?[]const u8 = null;
    var src_name: ?[]const u8 = null;
    var file_index: usize = 0;

    var i: usize = 1;
    while (i < args.len) : (i += 1) {
        if (std.mem.eql(u8, args[i], "--input")) { i += 1; input = args[i]; }
        else if (std.mem.eql(u8, args[i], "--output")) { i += 1; output = args[i]; }
        else if (std.mem.eql(u8, args[i], "--src-name")) { i += 1; src_name = args[i]; }
        else if (std.mem.eql(u8, args[i], "--file-index")) {
            i += 1;
            file_index = std.fmt.parseInt(usize, args[i], 10) catch {
                std.debug.print("zsx-gen: bad --file-index '{s}'\n", .{args[i]});
                return error.BadArgs;
            };
        } else {
            std.debug.print("zsx-gen: unknown arg '{s}'\n", .{args[i]});
            return error.BadArgs;
        }
    }

    if (input == null or output == null or src_name == null) {
        std.debug.print("usage: zsx-gen --input <path> --output <path> --src-name <name> --file-index <n>\n", .{});
        return error.MissingArgs;
    }

    const dir = std.Io.Dir.cwd();
    const src_bytes = try dir.readFileAlloc(io, input.?, a, .limited(10 * 1024 * 1024));
    const body = preprocess.preprocess(a, src_bytes, src_name.?, file_index) catch |e| {
        std.debug.print("zsx: failed to process {s}: {any}\n", .{ src_name.?, e });
        return e;
    };

    var out = std.array_list.Managed(u8).init(a);
    try writeFmt(a, &out, "// generated by zsx from {s}\n// do not edit by hand\n\n", .{src_name.?});
    try out.appendSlice(body);
    try out.appendSlice("\n\npub fn view(ui: anytype, c: anytype, ctx: anytype) void {\n");

    const uses_ui = std.mem.indexOf(u8, body, "ui.") != null or
        std.mem.indexOf(u8, body, "ui,") != null or
        std.mem.indexOf(u8, body, "ui)") != null;
    const uses_c = std.mem.indexOf(u8, body, "(c,") != null or
        std.mem.indexOf(u8, body, ", c,") != null or
        std.mem.indexOf(u8, body, "(c)") != null;
    const uses_ctx = std.mem.indexOf(u8, body, "ctx.") != null;

    if (!uses_ui) try out.appendSlice("    _ = ui;\n");
    if (!uses_c) try out.appendSlice("    _ = c;\n");
    if (!uses_ctx) try out.appendSlice("    _ = ctx;\n");
    try out.appendSlice(body);
    try out.appendSlice("\n}\n");

    const out_file = try dir.createFile(io, output.?, .{ .truncate = true });
    defer out_file.close(io);
    try out_file.writeStreamingAll(io, out.items);
}
