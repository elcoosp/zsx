//! `zig build golden` — render every view through the real pipeline and diff
//! against committed goldens. `-Dupdate-golden` rewrites the goldens.
//!
//! Both the diff and the `-Dupdate-golden` writer normalize the rendered
//! source through the canonical Zig formatter (`std.zig.Ast` + `renderAlloc`,
//! the same renderer `zig fmt` uses), so committed goldens are always
//! `zig fmt`-clean and a `zig fmt --check` pass over the tree can never drift
//! from `zig build golden`. Codegen output is already valid Zig — it is what
//! the compiler itself consumes — so the parse cannot fail for well-formed
//! views.

const std = @import("std");
const preprocess = @import("zsx_preprocess");

/// Format rendered codegen output exactly as `zig fmt` would. Returns the
/// input unchanged if parsing fails (defensive: keep goldens diffable even
/// for a future emitter bug, instead of blocking the whole gate).
fn zigFmt(a: std.mem.Allocator, src: []const u8) ![]const u8 {
    const sentinel = try a.dupeSentinel(u8, src, 0);
    const tree = std.zig.Ast.parse(a, sentinel, .{}) catch return src;
    return tree.renderAlloc(a) catch src;
}

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(a);
    const dir = std.Io.Dir.cwd();

    var root: []const u8 = ".";
    var update = false;
    var views = std.array_list.Managed([]const u8).init(a);

    var i: usize = 1;
    while (i < args.len) : (i += 1) {
        if (std.mem.eql(u8, args[i], "--root")) {
            i += 1;
            root = args[i];
        } else if (std.mem.eql(u8, args[i], "--update")) {
            update = true;
        } else if (std.mem.eql(u8, args[i], "--view")) {
            i += 1;
            try views.append(args[i]);
        } else {
            std.debug.print("golden: unknown arg '{s}'\n", .{args[i]});
            return error.BadArgs;
        }
    }
    if (views.items.len == 0) {
        std.debug.print("golden: no --view arguments\n", .{});
        return error.BadArgs;
    }

    const golden_dir = try std.fs.path.join(a, &.{ root, "spec", "golden" });
    if (update) try dir.createDirPath(io, golden_dir);

    var failed = std.array_list.Managed([]const u8).init(a);
    for (views.items, 0..) |rel, file_index| {
        const path = try std.fs.path.join(a, &.{ root, rel });
        const src = dir.readFileAlloc(io, path, a, .limited(10 * 1024 * 1024)) catch |e| {
            std.debug.print("golden: cannot read {s}: {s}\n", .{ rel, @errorName(e) });
            return error.ReadFailed;
        };
        const body = preprocess.preprocess(a, src, rel, file_index) catch |e| {
            std.debug.print("golden: failed to process {s}: {s}\n", .{ rel, @errorName(e) });
            return error.GenFailed;
        };
        const rendered_raw = try std.fmt.allocPrint(
            a,
            "// generated by zsx from {s}\n// do not edit by hand\n\n{s}",
            .{ rel, body },
        );
        const rendered = try zigFmt(a, rendered_raw);

        const stem = std.fs.path.stem(rel);
        const golden_path = try std.fs.path.join(a, &.{ golden_dir, try std.fmt.allocPrint(a, "{s}.zig", .{stem}) });

        if (update) {
            const out = try dir.createFile(io, golden_path, .{ .truncate = true });
            defer out.close(io);
            try out.writeStreamingAll(io, rendered);
            continue;
        }

        const expected = dir.readFileAlloc(io, golden_path, a, .limited(10 * 1024 * 1024)) catch {
            std.debug.print("golden: missing {s} (run `zig build golden -Dupdate-golden`)\n", .{golden_path});
            try failed.append(rel);
            continue;
        };
        if (!std.mem.eql(u8, expected, rendered)) {
            std.debug.print("golden: mismatch {s} vs {s}\n", .{ rel, golden_path });
            std.debug.print("{s}\n", .{firstDiff(expected, rendered)});
            try failed.append(rel);
        }
    }

    if (update) {
        std.debug.print("golden: updated {d} file(s)\n", .{views.items.len});
        return;
    }
    if (failed.items.len != 0) {
        std.debug.print("golden: {d} mismatch(es)\n", .{failed.items.len});
        return error.GoldenMismatch;
    }
    std.debug.print("golden: ok ({d} files)\n", .{views.items.len});
}

fn firstDiff(expected: []const u8, actual: []const u8) []const u8 {
    var line: usize = 1;
    var col: usize = 1;
    const n = @min(expected.len, actual.len);
    var i: usize = 0;
    while (i < n) : (i += 1) {
        if (expected[i] != actual[i]) break;
        if (expected[i] == '\n') {
            line += 1;
            col = 1;
        } else col += 1;
    }
    return std.fmt.allocPrint(std.heap.page_allocator, "  first difference at line {d}, col {d}", .{ line, col }) catch "  (diff)";
}
